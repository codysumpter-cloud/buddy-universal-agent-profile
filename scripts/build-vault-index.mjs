#!/usr/bin/env node
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { buildIndex } from "../packages/buap-knowledge-vault/dist/index.js";

const defaultVaultPath = path.join(os.homedir(), "Prismtek", "knowledge-vault");
const vaultPath = path.resolve(process.env.KNOWLEDGE_VAULT_PATH || process.argv[2] || defaultVaultPath);
const index = await buildIndex(vaultPath);

const jsonPath = path.join(vaultPath, "KNOWLEDGE_VAULT_INDEX.json");
const markdownPath = path.join(vaultPath, "KNOWLEDGE_VAULT_INDEX.md");

function markdownLink(relativePath) {
  return relativePath.includes(" ") ? `<${relativePath}>` : relativePath;
}

const lines = [
  "# Knowledge Vault Index",
  "",
  `Generated: ${index.generatedAt}`,
  `Vault path: \`${index.vaultPath}\``,
  `Notes indexed: ${index.entries.length}`,
  "",
  "This file is generated by `node scripts/build-vault-index.mjs` from the BUAP repo.",
  "",
  "## Notes",
  ""
];

for (const entry of index.entries) {
  const excerpt = entry.excerpt ? ` — ${entry.excerpt}` : "";
  lines.push(`- [${entry.path}](${markdownLink(entry.path)}) — **${entry.title}**${excerpt}`);
}

await fs.writeFile(jsonPath, `${JSON.stringify(index, null, 2)}\n`, "utf8");
await fs.writeFile(markdownPath, `${lines.join("\n")}\n`, "utf8");

console.log("Knowledge vault index built");
console.log(JSON.stringify({ vaultPath, entries: index.entries.length, jsonPath, markdownPath }, null, 2));
